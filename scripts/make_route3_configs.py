#!/usr/bin/env python3
"""Writes ``configs/videos/fixed_<v>.yaml`` for route three (``spec docs/17`` T66):
frames mode over ``fixed-images``, exactly the labelled ordinals of each video
(``frame_ordinals``, so GPU time goes only to frames that can be scored),
``assumed_fps 1.0``, audio unavailable, hinted pass only.

Usage::

    python scripts/make_route3_configs.py --videos 14,1 [--labels-dir ~/Downloads/logo2.yolov11/train/labels]
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

_STEM = re.compile(r"^(\d+)_frame_(\d+)")


def labelled_ordinals(labels_dir: Path, video: str) -> list[int]:
    out = set()
    for f in Path(labels_dir).expanduser().glob(f"{video}_frame_*.txt"):
        m = _STEM.match(f.name)
        if m and m.group(1) == video and f.read_text(encoding="utf-8").strip():
            out.add(int(m.group(2)))
    return sorted(out)


def render(video: str, ordinals: list[int], frames_dir: str) -> str:
    return (
        f"# Route three (17 T66), generated by scripts/make_route3_configs.py: the {len(ordinals)} labelled\n"
        f"# ordinals of fixed-images video {video}. Frames mode has no audio; hinted pass only (T64 does not\n"
        "# need the blind pass on route three).\n"
        f"video_id: \"{video}\"\n"
        "source: null\n"
        "channel: null\n"
        "channel_brand: null\n"
        "watermark_regions_ref: null\n"
        f"frame_ordinals: [{', '.join(str(o) for o in ordinals)}]\n"
        "overrides:\n"
        "  ingest:\n"
        "    mode: frames\n"
        "    frames:\n"
        f"      dir: {frames_dir}\n"
        "      assumed_fps: 1.0\n"
        "  vlm:\n"
        "    blind_pass: false\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--videos", required=True)
    ap.add_argument("--labels-dir", default="~/Downloads/logo2.yolov11/train/labels")
    ap.add_argument("--frames-dir", default="fixed-images")
    ap.add_argument("--out", default="configs/videos")
    args = ap.parse_args(argv)
    for v in args.videos.split(","):
        ords = labelled_ordinals(Path(args.labels_dir), v.strip())
        if not ords:
            print(f"video {v}: no labelled frames found, skipped")
            continue
        path = Path(args.out) / f"fixed_{v.strip()}.yaml"
        path.write_text(render(v.strip(), ords, args.frames_dir), encoding="utf-8")
        print(f"wrote {path} ({len(ords)} labelled ordinals)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
