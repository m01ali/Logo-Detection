#!/usr/bin/env python3
"""T19 (``spec docs/08``): reads a run's ``merge_log.jsonl`` and writes
``reports/merge_distributions.md`` + ``.csv`` — 20-bin histograms of
``iou``/``contain``/``area_ratio`` for the ``failed_size_precondition``
population and of ``smaller_fraction`` for the ``skipped_area_floor``
population, plus the share of overlapping pairs the area floor skipped and
the extra VLM calls that implies. This is the evidence for re-setting
``merge.min_merge_area``/thresholds after the first full run.

Run with ``merge.log_failed_pairs: false`` first (which only persists
"merged" pairs to disk) and this script has nothing to read from the
non-merge populations — set it back to ``true`` for the run you want to
ablate.

Usage::

    python eval/merge_ablation.py --run runs/<video_id>/<run_id>
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

N_BINS = 20


def read_merge_log(run_dir: Path) -> tuple[dict, list[dict]]:
    path = run_dir / "merge_log.jsonl"
    header: dict = {}
    rows: list[dict] = []
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            if obj.get("_header"):
                header = obj
                continue
            rows.append(obj)
    return header, rows


def histogram(values: list[float], lo: float, hi: float, n_bins: int = N_BINS) -> list[dict]:
    if hi <= lo:
        hi = lo + 1.0
    width = (hi - lo) / n_bins
    counts = [0] * n_bins
    for v in values:
        idx = int((v - lo) / width)
        idx = min(max(idx, 0), n_bins - 1)
        counts[idx] += 1
    return [{"bin_lo": round(lo + i * width, 6), "bin_hi": round(lo + (i + 1) * width, 6), "count": counts[i]}
            for i in range(n_bins)]


def analyse(header: dict, rows: list[dict]) -> dict:
    t_iou = header.get("iou_threshold", 0.70)
    t_contain = header.get("containment_threshold", 0.90)
    t_area_ratio = header.get("area_ratio_threshold", 0.80)
    t_min_merge_area = header.get("min_merge_area", 0.0004)

    failed = [r for r in rows if r["outcome"] == "failed_size_precondition"]
    floor = [r for r in rows if r["outcome"] == "skipped_area_floor"]
    overlapping = [r for r in rows if r["iou"] >= t_iou or r["contain"] >= t_contain]
    floor_overlapping = [r for r in floor if r["iou"] >= t_iou or r["contain"] >= t_contain]
    floor_would_have_merged = [r for r in floor_overlapping if r["area_ratio"] >= t_area_ratio]

    floor_smaller_fractions = [r["smaller_fraction"] for r in floor]
    floor_hist_hi = max(floor_smaller_fractions, default=t_min_merge_area)
    floor_hist_hi = max(floor_hist_hi, t_min_merge_area)

    return {
        "thresholds": {"iou_threshold": t_iou, "containment_threshold": t_contain,
                        "area_ratio_threshold": t_area_ratio, "min_merge_area": t_min_merge_area},
        "n_pairs_evaluated": len(rows),
        "n_failed_size_precondition": len(failed),
        "n_skipped_area_floor": len(floor),
        "n_overlapping_pairs": len(overlapping),
        "n_floor_overlapping": len(floor_overlapping),
        "floor_share_of_overlapping": (len(floor_overlapping) / len(overlapping)) if overlapping else 0.0,
        "n_floor_would_have_merged": len(floor_would_have_merged),
        "histograms": {
            "iou_failed_size_precondition": histogram([r["iou"] for r in failed], 0.0, 1.0),
            "contain_failed_size_precondition": histogram([r["contain"] for r in failed], 0.0, 1.0),
            "area_ratio_failed_size_precondition": histogram([r["area_ratio"] for r in failed], 0.0, 1.0),
            "smaller_fraction_skipped_area_floor": histogram(floor_smaller_fractions, 0.0, floor_hist_hi),
        },
    }


def render_markdown(run_dir: Path, stats: dict) -> str:
    t = stats["thresholds"]
    lines = [
        f"# Merge distributions — `{run_dir}`",
        "",
        "Generated by `eval/merge_ablation.py` from `merge_log.jsonl` (T19, `spec docs/08`).",
        "",
        f"Thresholds this run used: iou >= {t['iou_threshold']}, containment >= {t['containment_threshold']}, "
        f"area_ratio >= {t['area_ratio_threshold']}, min_merge_area = {t['min_merge_area']}.",
        "",
        "## Summary",
        "",
        f"- Pairs evaluated: {stats['n_pairs_evaluated']}",
        f"- `failed_size_precondition`: {stats['n_failed_size_precondition']}",
        f"- `skipped_area_floor`: {stats['n_skipped_area_floor']}",
        f"- Overlapping pairs (iou/containment over threshold): {stats['n_overlapping_pairs']}",
        f"- Of those, skipped by the area floor: {stats['n_floor_overlapping']} "
        f"({stats['floor_share_of_overlapping']:.1%})",
        f"- Area-floor pairs that would otherwise have merged (extra VLM calls the floor causes): "
        f"{stats['n_floor_would_have_merged']}",
        "",
    ]
    for name, bins in stats["histograms"].items():
        lines.append(f"## `{name}`")
        lines.append("")
        lines.append("| bin | count |")
        lines.append("|-----|-------|")
        for b in bins:
            lines.append(f"| [{b['bin_lo']}, {b['bin_hi']}) | {b['count']} |")
        lines.append("")
    return "\n".join(lines) + "\n"


def write_csv(path: Path, stats: dict) -> None:
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["population", "bin_lo", "bin_hi", "count"])
        for name, bins in stats["histograms"].items():
            for b in bins:
                w.writerow([name, b["bin_lo"], b["bin_hi"], b["count"]])


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", required=True, help="Run directory, e.g. runs/<video_id>/<run_id>")
    args = ap.parse_args()

    run_dir = Path(args.run)
    header, rows = read_merge_log(run_dir)
    if not rows:
        print(f"no pairs in {run_dir / 'merge_log.jsonl'} "
              f"(merge.enabled: false, or merge.log_failed_pairs: false dropped the non-merged population)")
    stats = analyse(header, rows)

    reports_dir = run_dir / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    md_path = reports_dir / "merge_distributions.md"
    csv_path = reports_dir / "merge_distributions.csv"
    md_path.write_text(render_markdown(run_dir, stats), encoding="utf-8")
    write_csv(csv_path, stats)
    print(f"wrote {md_path} and {csv_path} ({stats['n_pairs_evaluated']} pairs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
