#!/usr/bin/env python3
"""T24 (``spec docs/09``): reads a run's ``refinement.jsonl`` (+ ``ocr.jsonl``
if present) and writes ``reports/refinement.md`` — total rows; share by
``refinement_status``; fallback rate = 1 - share(applied); breakdown of
``rejected_safety_check`` by failing check; ``oversized_region`` count; mean
``refinement_area_ratio`` for applied rows; and the "OCR-brand fuzzy match
before vs after refinement" count (applied rows where the loose-crop OCR
call, logged in ``refinement.jsonl``'s own ``ocr_boxes``, found a brand but
the MM4 tight-crop verification pass (``ocr.jsonl``'s ``ocr_brand_match``)
didn't, and vice versa). That second half only has real data once MM4 lands
(``ocr_brand_match`` is null until then); the report says so rather than
faking a number.

If the fallback rate is very high (> 90%), the report flags the module as
inert, as the client asked (18 July).

Usage::

    python eval/refinement_report.py --run runs/<video_id>/<run_id>
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

INERT_FALLBACK_RATE = 0.90


def read_jsonl(path: Path) -> list[dict]:
    rows: list[dict] = []
    if not path.exists():
        return rows
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            if obj.get("_header"):
                continue
            rows.append(obj)
    return rows


def _loose_crop_brand_found(row: dict) -> bool:
    return any(b.get("matched_brand") for b in (row.get("ocr_boxes") or []))


def analyse(rows: list[dict], ocr_rows: list[dict]) -> dict:
    n = len(rows)
    status_counts = Counter(r["refinement_status"] for r in rows)
    applied = status_counts.get("applied", 0)
    fallback_rate = (1 - applied / n) if n else 0.0

    rejected = [r for r in rows if r["refinement_status"] == "rejected_safety_check"]
    failing_checks: Counter = Counter()
    for r in rejected:
        for check, ok in (r.get("safety_results") or {}).items():
            if not ok:
                failing_checks[check] += 1

    applied_ratios = [r["refinement_area_ratio"] for r in rows
                       if r["refinement_status"] == "applied" and r["refinement_area_ratio"] is not None]
    mean_applied_area_ratio = (sum(applied_ratios) / len(applied_ratios)) if applied_ratios else None

    ocr_by_det = {r["det_id"]: r for r in ocr_rows}
    ocr_matching_available = any(r.get("ocr_brand_match") is not None for r in ocr_rows)
    applied_rows = [r for r in rows if r["refinement_status"] == "applied"]
    tight_found_not_loose = loose_found_not_tight = 0
    for r in applied_rows:
        loose_found = _loose_crop_brand_found(r)
        tight_found = bool(ocr_by_det.get(r["det_id"], {}).get("ocr_brand_match"))
        if tight_found and not loose_found:
            tight_found_not_loose += 1
        if loose_found and not tight_found:
            loose_found_not_tight += 1

    return {
        "n_rows": n, "status_counts": dict(status_counts), "applied": applied,
        "fallback_rate": fallback_rate, "failing_checks": dict(failing_checks),
        "oversized_region": status_counts.get("oversized_region", 0),
        "no_candidate": status_counts.get("no_candidate", 0),
        "rejected_safety_check": status_counts.get("rejected_safety_check", 0),
        "mean_applied_area_ratio": mean_applied_area_ratio,
        "ocr_matching_available": ocr_matching_available,
        "n_applied_rows": len(applied_rows),
        "tight_found_not_loose": tight_found_not_loose,
        "loose_found_not_tight": loose_found_not_tight,
    }


def render_markdown(run_dir: Path, stats: dict) -> str:
    lines = [
        f"# Refinement report — `{run_dir}`",
        "",
        "Generated by `eval/refinement_report.py` from `refinement.jsonl` (T24, `spec docs/09`).",
        "",
        "## Summary",
        "",
        f"- Total rows: {stats['n_rows']}",
        f"- Fallback rate (1 - share applied): {stats['fallback_rate']:.1%}",
        "",
        "| status | count | share |",
        "|--------|-------|-------|",
    ]
    for status, count in sorted(stats["status_counts"].items()):
        share = count / stats["n_rows"] if stats["n_rows"] else 0.0
        lines.append(f"| {status} | {count} | {share:.1%} |")
    lines += ["", "## `rejected_safety_check` breakdown by failing check", ""]
    if stats["failing_checks"]:
        lines += ["| check | count |", "|-------|-------|"]
        for check, count in sorted(stats["failing_checks"].items(), key=lambda kv: -kv[1]):
            lines.append(f"| {check} | {count} |")
    else:
        lines.append("(no `rejected_safety_check` rows)")
    lines += [
        "",
        "## Applied rows",
        "",
        f"- Mean `refinement_area_ratio`: "
        f"{stats['mean_applied_area_ratio']:.4f}" if stats["mean_applied_area_ratio"] is not None
        else "- Mean `refinement_area_ratio`: n/a (no applied rows)",
        "",
        "## OCR-brand fuzzy match, before vs after refinement (18 July)",
        "",
    ]
    if stats["ocr_matching_available"]:
        lines += [
            f"- Applied rows: {stats['n_applied_rows']}",
            f"- Brand found on the tight crop (MM4) but not the loose crop: {stats['tight_found_not_loose']}",
            f"- Brand found on the loose crop but not the tight crop (MM4): {stats['loose_found_not_tight']}",
        ]
    else:
        lines.append(
            "Not computable yet: `ocr.jsonl`'s `ocr_brand_match` is still null for every row "
            "(OCR brand matching is MM4, `spec docs/10`, T26-T29). Re-run this report once MM4 lands.")
    lines.append("")
    if stats["fallback_rate"] > INERT_FALLBACK_RATE:
        lines += [
            "## Flag",
            "",
            f"Fallback rate {stats['fallback_rate']:.1%} exceeds {INERT_FALLBACK_RATE:.0%} — "
            "heuristic 2 is effectively inert on this run.",
            "",
        ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--run", required=True, help="Run directory, e.g. runs/<video_id>/<run_id>")
    args = ap.parse_args()

    run_dir = Path(args.run)
    rows = read_jsonl(run_dir / "refinement.jsonl")
    ocr_rows = read_jsonl(run_dir / "ocr.jsonl")
    stats = analyse(rows, ocr_rows)

    reports_dir = run_dir / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    md_path = reports_dir / "refinement.md"
    md_path.write_text(render_markdown(run_dir, stats), encoding="utf-8")
    print(f"wrote {md_path} ({stats['n_rows']} rows, fallback rate {stats['fallback_rate']:.1%})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
